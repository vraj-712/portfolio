/**
 * Regenerates api/fonts.data.ts — the base64-inlined fonts the /api/og function
 * renders with. We inline them (rather than reading api/assets/*.ttf at runtime)
 * so the serverless bundle needs no file-asset tracing: a bundled JS import is
 * always included, whereas files loaded via `new URL(..., import.meta.url)` rely
 * on Vercel's tracer picking them up — which silently failed for these fonts.
 *
 * Run:  node scripts/gen-og-fonts.mjs   (or: bun scripts/gen-og-fonts.mjs)
 * after changing the TTFs in api/assets/.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const assets = join(root, 'api', 'assets');
const b64 = (f) => readFileSync(join(assets, f)).toString('base64');

const out = `/* AUTO-GENERATED by scripts/gen-og-fonts.mjs — do not edit by hand.
 * Real site fonts, base64-inlined so the OG function needs zero file-asset
 * tracing at deploy time (a bundled JS import is always included, unlike files
 * read via import.meta.url).
 *   - Bricolage Grotesque Bold  → display headline / wordmark (--font-display)
 *   - Space Mono Regular + Bold → eyebrow / subtitle / meta   (--font-mono)
 */
export const displayBold = '${b64('BricolageGrotesque-Bold.ttf')}';
export const monoRegular = '${b64('SpaceMono-Regular.ttf')}';
export const monoBold = '${b64('SpaceMono-Bold.ttf')}';
`;

writeFileSync(join(root, 'api', 'fonts.data.ts'), out);
console.log(`Wrote api/fonts.data.ts (${(out.length / 1024) | 0} KB)`);
